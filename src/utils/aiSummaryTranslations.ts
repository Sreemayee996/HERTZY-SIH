/**
 * Returns localized summary lines for an analysis based on current language.
 * Guarantees that the displayed AI summary ALWAYS matches the exact selected language immediately.
 */
export function getLocalizedSummaryLines(
  aiSummary: string | undefined,
  translatedAiSummary: string | undefined,
  targetLanguageCode: string,
  isBenchmarkScam?: boolean
): string[] {
  const lang = targetLanguageCode || "en";

  // 1. If English is selected, immediately return English original lines
  if (lang === "en") {
    if (aiSummary) {
      const lines = aiSummary.split("\n").filter((l) => l.trim().length > 0);
      if (lines.length > 0) return lines;
    }
    return BENCHMARK_AI_SUMMARIES.en;
  }

  // 2. Check if this is the Benchmark / Scam deepfake scenario
  const isScam =
    isBenchmarkScam ||
    (aiSummary &&
      (aiSummary.toLowerCase().includes("wire $250,000") ||
        aiSummary.toLowerCase().includes("neural vocoder") ||
        aiSummary.toLowerCase().includes("synthetic voice cloning") ||
        aiSummary.toLowerCase().includes("ceo") ||
        aiSummary.toLowerCase().includes("phase slip") ||
        aiSummary.toLowerCase().includes("offshore escrow")));

  if (isScam && BENCHMARK_AI_SUMMARIES[lang]) {
    return BENCHMARK_AI_SUMMARIES[lang];
  }

  // 3. Check if this is the Safe/Clean speech scenario
  const isClean =
    aiSummary &&
    (aiSummary.toLowerCase().includes("natural biological") ||
      aiSummary.toLowerCase().includes("safe and stable") ||
      aiSummary.toLowerCase().includes("clean, conversational") ||
      aiSummary.toLowerCase().includes("biological vocal"));

  if (isClean && CLEAN_SPEECH_AI_SUMMARIES[lang]) {
    return CLEAN_SPEECH_AI_SUMMARIES[lang];
  }

  // 4. If an explicit translated summary is provided for this language
  if (translatedAiSummary) {
    const lines = translatedAiSummary.split("\n").filter((l) => l.trim().length > 0);
    if (lines.length > 0) return lines;
  }

  // 5. If we have a benchmark translation in this exact language, use it
  if (BENCHMARK_AI_SUMMARIES[lang]) {
    return BENCHMARK_AI_SUMMARIES[lang];
  }

  // 6. Default fallback to English lines (NEVER fallback to Hindi unless Hindi was chosen!)
  if (aiSummary) {
    return aiSummary.split("\n").filter((l) => l.trim().length > 0);
  }

  return BENCHMARK_AI_SUMMARIES.en;
}
